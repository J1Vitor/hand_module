    def le_geotiff_escreve_bin(self):
        """This function reads the .tif file sent by the user and converts it to binary .rst type for reading in fortran."""
        # Clear temp folder
        self.del_temp_files()

        # Define the paths for the temporary GeoTIFF files
        basin_temp_tif = self.current_dir + r'\temp\bacia_temp.tif'
        DEM_temp_tif = self.current_dir + r'\temp\MDE_temp.tif'
        dir_temp_tif = self.current_dir + r'\temp\dir_temp.tif'
        drainage_temp_tif = self.current_dir + r'\temp\drenagem_temp.tif'

        self.dlg_hand.progressBar.setValue(5)
        # Convert the input files to the correct data types in temporary copies
        gdal.Translate(basin_temp_tif, self.dlg_hand.cb_01.currentLayer(
        ).source(), outputType=gdal.GDT_Int16)

        # store geotransform and projection
        dataset = gdal.Open(self.dlg_hand.cb_01.currentLayer().source())
        self.projection = dataset.GetProjection()
        dataset = None  # Close the dataset

        self.dlg_hand.progressBar.setValue(10)
        gdal.Translate(DEM_temp_tif, self.dlg_hand.cb_02.currentLayer(
        ).source(), outputType=gdal.GDT_Float32)
        self.dlg_hand.progressBar.setValue(15)
        gdal.Translate(dir_temp_tif, self.dlg_hand.cb_03.currentLayer(
        ).source(), outputType=gdal.GDT_Int16)
        self.dlg_hand.progressBar.setValue(20)
        gdal.Translate(drainage_temp_tif, self.dlg_hand.cb_04.currentLayer(
        ).source(), outputType=gdal.GDT_Int16)
        self.dlg_hand.progressBar.setValue(25)

        # Binary rst files
        basin_rst = self.current_dir + r'\temp\bacia.rst'
        DEM_rst = self.current_dir + r'\temp\MDE.rst'
        dir_rst = self.current_dir + r'\temp\dir.rst'
        drainage_rst = self.current_dir + r'\temp\drenagem.rst'

        # Convert the temporary copies to RST format
        gdal.Translate(basin_rst, basin_temp_tif, format="RST")
        self.dlg_hand.progressBar.setValue(30)

        # Convert DEM
        gdal.Translate(DEM_rst, DEM_temp_tif, format="RST")
        self.dlg_hand.progressBar.setValue(35)

        # Convert flow directions
        gdal.Translate(dir_rst, dir_temp_tif, format="RST")
        self.dlg_hand.progressBar.setValue(40)

        # Convert drainage network
        gdal.Translate(drainage_rst, drainage_temp_tif, format="RST")
        self.dlg_hand.progressBar.setValue(50)

