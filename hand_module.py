    def carregaArquivos(self, combobox, file_type="raster"):
        """This function is used to add the files sent by the user to the plugin."""
        # Define the variables and settings of the file selection window
        file_ = None
        options = QFileDialog.Options()

        while True:  # Loop until the user selects a file or cancels

            # Dialog window with the User
            if file_type == "raster":
                file_, _ = QFileDialog.getOpenFileName(
                    None, "Select a file!", "", "GeoTIFF (*.tif)", options=options)
                if not file_:
                    result = self.msgs[self.current_lang]['no_file_selected']
                    reply = QMessageBox.warning(
                        self.dlg_hand, self.msgs[self.current_lang]['warning_title'], result, QMessageBox.Ok)
                    if reply == QMessageBox.Ok:
                        break

                # If the raster is not in the project, add it
                if file_ not in [layer.source() for layer in QgsProject.instance().mapLayers().values()]:
                    layer = QgsRasterLayer(
                        file_, os.path.basename(file_), "gdal")
                    QgsProject.instance().addMapLayer(layer)

                # Add the file to the combo box
                combobox.setLayer(layer)

                return file_

